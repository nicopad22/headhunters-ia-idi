#!/usr/bin/env python3.12
"""Generate firmware/include/game_data.h from data/game_data.json."""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA_PATH = ROOT / "data" / "game_data.json"
OUT_PATH = ROOT / "firmware" / "include" / "game_data.h"

MODALITY_ENUM = {
    "H": "MOD_HUMANO",
    "H_IA": "MOD_HUMANO_IA",
    "IA": "MOD_IA_SOLA",
}

MYSTERY_EFFECT_ENUM = {
    "ADD_MONEY": "MYS_ADD_MONEY",
    "BONUS_PER_MODALITY": "MYS_BONUS_PER_MODALITY",
    "PENALTY_PER_MODALITY": "MYS_PENALTY_PER_MODALITY",
    "PENALTY_LOW_IA": "MYS_PENALTY_LOW_IA",
    "FORCE_RECEPTION_NO_PAY": "MYS_FORCE_RECEPTION_NO_PAY",
    "ENABLE_PAYOUT_RECEPTION": "MYS_ENABLE_PAYOUT_RECEPTION",
    "BOARD_INFO_ONLY": "MYS_BOARD_INFO_ONLY",
    "NEXT_HIRE_DISCOUNT": "MYS_NEXT_HIRE_DISCOUNT",
    "UPGRADE_HUMAN_TO_HYBRID": "MYS_UPGRADE_HUMAN_TO_HYBRID",
    "RETURN_CANDIDATE_HALF": "MYS_RETURN_CANDIDATE_HALF",
    "TRIVIA_CONFIRM": "MYS_TRIVIA_CONFIRM",
}


def c_str(text: str) -> str:
    escaped = text.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{escaped}"'


def main() -> None:
    data = json.loads(DATA_PATH.read_text(encoding="utf-8"))
    game = data["game"]
    occupations = data["occupations"]
    candidates = data["candidates"]
    companies = data["companies"]
    mystery_cards = data["mystery_cards"]

    lines: list[str] = [
        "#pragma once",
        "",
        "#include <stdint.h>",
        "",
        "// Auto-generated by scripts/generate_header.py from data/game_data.json",
        "// Do not edit manually; update data/game_data.json and re-run the generator.",
        "",
        f"constexpr uint8_t NUM_PLAYERS = {game['players_count']};",
        f"constexpr uint8_t NUM_OCCUPATIONS = {len(occupations)};",
        f"constexpr uint8_t NUM_CANDIDATES = {len(candidates)};",
        f"constexpr uint8_t NUM_MYSTERY_CARDS = {len(mystery_cards)};",
        f"constexpr uint8_t ROLES_PER_COMPANY = {len(companies[0]['required_occupation_ids'])};",
        f"constexpr int16_t STARTING_MONEY = {game['starting_money']};",
        f"constexpr uint8_t STARTING_PROFITABILITY = {game['starting_profitability']};",
        f"constexpr uint8_t WIN_PROFITABILITY_TARGET = {game['win_profitability_target']};",
        f"constexpr int16_t RECEPTION_BASE_PAYOUT = {game['reception_base_payout']};",
        f"constexpr int16_t RECEPTION_PAYOUT_PER_LEVEL = {game['reception_payout_per_level']};",
        f"constexpr int16_t INSIGHT_COST = {game['insight_cost']};",
        "",
        "enum Modality : uint8_t {",
        "  MOD_HUMANO = 0,",
        "  MOD_HUMANO_IA = 1,",
        "  MOD_IA_SOLA = 2,",
        "};",
        "",
        "enum MysteryEffect : uint8_t {",
        "  MYS_ADD_MONEY = 0,",
        "  MYS_BONUS_PER_MODALITY,",
        "  MYS_PENALTY_PER_MODALITY,",
        "  MYS_PENALTY_LOW_IA,",
        "  MYS_FORCE_RECEPTION_NO_PAY,",
        "  MYS_ENABLE_PAYOUT_RECEPTION,",
        "  MYS_BOARD_INFO_ONLY,",
        "  MYS_NEXT_HIRE_DISCOUNT,",
        "  MYS_UPGRADE_HUMAN_TO_HYBRID,",
        "  MYS_RETURN_CANDIDATE_HALF,",
        "  MYS_TRIVIA_CONFIRM,",
        "};",
        "",
        "struct OccupationDef {",
        "  uint8_t id;",
        "  const char* isco;",
        "  const char* room;",
        "  const char* role;",
        "  float oit_score;",
        "  const char* oit_level;",
        "  Modality ideal_modality;",
        "  uint32_t nfc_uid_hash; // 0 if unassigned",
        "};",
        "",
        "struct CandidateDef {",
        "  uint8_t id;",
        "  uint8_t occupation_id;",
        "  Modality modality;",
        "  const char* name;",
        "  int16_t cost;",
        "  uint8_t profitability;",
        "  uint32_t nfc_uid_hash; // 0 if unassigned",
        "};",
        "",
        "struct CompanyDef {",
        "  uint8_t id;",
        "  const char* name;",
        "  const char* founder;",
        "  uint8_t required_occupations[ROLES_PER_COMPANY];",
        "};",
        "",
        "struct MysteryCardDef {",
        "  uint8_t id;",
        "  const char* title;",
        "  MysteryEffect effect;",
        "  Modality target_modality;",
        "  int16_t value;",
        "  uint32_t nfc_uid_hash; // 0 if unassigned",
        "};",
        "",
        "static const OccupationDef OCCUPATIONS[NUM_OCCUPATIONS] = {",
    ]

    for occ in occupations:
        uid_val = f"0x{occ['nfc_uid']}" if occ.get("nfc_uid") else "0"
        lines.append(
            f"  {{{occ['id']}, {c_str(occ['isco'])}, {c_str(occ['room'])}, "
            f"{c_str(occ['role'])}, {occ['oit_score']:.2f}f, {c_str(occ['oit_level'])}, "
            f"{MODALITY_ENUM[occ['ideal_modality']]}, {uid_val}}},"
        )
    lines.append("};")
    lines.append("")
    lines.append("static const CandidateDef CANDIDATES[NUM_CANDIDATES] = {")

    for cand in candidates:
        uid_val = f"0x{cand['nfc_uid']}" if cand.get("nfc_uid") else "0"
        lines.append(
            f"  {{{cand['id']}, {cand['occupation_id']}, {MODALITY_ENUM[cand['modality']]}, "
            f"{c_str(cand['name'])}, {cand['cost']}, {cand['profitability']}, {uid_val}}},"
        )
    lines.append("};")
    lines.append("")
    lines.append("static const CompanyDef COMPANIES[NUM_PLAYERS] = {")

    for comp in companies:
        req = ", ".join(str(x) for x in comp["required_occupation_ids"])
        lines.append(
            f"  {{{comp['id']}, {c_str(comp['name'])}, {c_str(comp['founder'])}, {{{req}}}}},"
        )
    lines.append("};")
    lines.append("")
    lines.append("static const MysteryCardDef MYSTERY_CARDS[NUM_MYSTERY_CARDS] = {")

    for card in mystery_cards:
        uid_val = f"0x{card['nfc_uid']}" if card.get("nfc_uid") else "0"
        mod = MODALITY_ENUM.get(card.get("modality", "H"), "MOD_HUMANO")
        lines.append(
            f"  {{{card['id']}, {c_str(card['title'])}, {MYSTERY_EFFECT_ENUM[card['effect']]}, "
            f"{mod}, {card['value']}, {uid_val}}},"
        )
    lines.append("};")
    lines.append("")

    OUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUT_PATH.write_text("\n".join(lines), encoding="utf-8")
    print(f"Generated {OUT_PATH}")


if __name__ == "__main__":
    main()
